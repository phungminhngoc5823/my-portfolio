#!/usr/bin/env python3
"""Generate src/data/imageSizes.ts from public/images (run after adding or replacing images)."""
import os, json
from PIL import Image
root = os.path.join(os.path.dirname(__file__), '..')
base = os.path.join(root, 'public', 'images')
sizes = {}
for d, _, files in os.walk(base):
    for f in files:
        if f.lower().endswith(('.jpg', '.jpeg', '.png', '.webp')):
            p = os.path.join(d, f)
            with Image.open(p) as im:
                sizes[os.path.relpath(p, base).replace(os.sep, '/')] = [im.width, im.height]
out = os.path.join(root, 'src', 'data', 'imageSizes.ts')
with open(out, 'w', encoding='utf8') as fh:
    fh.write('// Generated by scripts/gen-image-sizes.py. Do not edit by hand.\n')
    fh.write('export const IMAGE_SIZES: Record<string, [number, number]> = ' + json.dumps(sizes, indent=2, sort_keys=True) + ';\n\n')
    fh.write(r"""const cache = new Map<string, { width: number; height: number } | undefined>();

// Standalone builds inline images as data URIs, so read the size from the image header instead.
const sizeFromDataUri = (src: string): { width: number; height: number } | undefined => {
  try {
    const b64 = src.slice(src.indexOf(',') + 1, src.indexOf(',') + 1 + 340000);
    const bin = atob(b64.slice(0, b64.length - (b64.length % 4)));
    const b = (n: number) => bin.charCodeAt(n);
    if (b(0) === 0x89 && b(1) === 0x50) return { width: (b(16) << 24) | (b(17) << 16) | (b(18) << 8) | b(19), height: (b(20) << 24) | (b(21) << 16) | (b(22) << 8) | b(23) };
    let i = 2;
    while (i + 9 < bin.length) {
      if (b(i) !== 0xff) { i += 1; continue; }
      const m = b(i + 1);
      if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc) return { height: (b(i + 5) << 8) | b(i + 6), width: (b(i + 7) << 8) | b(i + 8) };
      i += 2 + ((b(i + 2) << 8) | b(i + 3));
    }
  } catch { /* fall through */ }
  return undefined;
};

export const imgSize = (src: string): { width: number; height: number } | undefined => {
  if (!src) return undefined;
  if (cache.has(src)) return cache.get(src);
  let size: { width: number; height: number } | undefined;
  if (src.startsWith('data:')) size = sizeFromDataUri(src);
  else {
    const hit = IMAGE_SIZES[src.replace(/^(\.\/|\/)?images\//, '')];
    size = hit ? { width: hit[0], height: hit[1] } : undefined;
  }
  cache.set(src, size);
  return size;
};
""")
print(len(sizes), 'images')
